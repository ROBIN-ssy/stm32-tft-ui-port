/**
  * @brief  This function handles DMA1 Stream4 interrupt request.
  * @note   SPI2_TX 使用 DMA1 Stream4 / Channel0 发送 KK_OLED 的页数据。
  *         这里只做事件转发，所有传输状态都由 kk_oled_driver.c 维护。
  * @param  None
  * @retval None
  */
void DMA1_Stream4_IRQHandler(void)
{
  if (DMA_GetITStatus(DMA1_Stream4, DMA_IT_TCIF4) != RESET)
  {
    DMA_ClearITPendingBit(DMA1_Stream4, DMA_IT_TCIF4);
    OLED_DriverHandleMemTxComplete();
  }
  if (DMA_GetITStatus(DMA1_Stream4, DMA_IT_TEIF4) != RESET)
  {
    DMA_ClearITPendingBit(DMA1_Stream4, DMA_IT_TEIF4);
    OLED_DriverHandleError();
  }
}

